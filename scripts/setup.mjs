#!/usr/bin/env node
// One-command local setup:  npm run setup
//
//   1. Generates the local secrets in docker/.env (git-ignored) if they're missing.
//   2. Starts Docker: self-hosted Convex, n8n (+ task runner), Mailpit.
//      n8n-bootstrap imports the credentials and workflows and publishes them.
//   3. Points the Convex CLI at the local backend (.env.local) and sets the
//      deployment's environment variables.
//   4. Pushes the Convex functions and schema.
//
// Safe to re-run. Flags:
//   --clerk-jwt-template   create a minimal "convex" JWT template in your Clerk
//                          dev instance (only if you don't use Clerk's Convex integration)
//   --skip-docker          don't touch Docker (CI / you manage it yourself)

import { spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync } from "node:fs";
import bcrypt from "bcryptjs";
import { readEnvFile, updateEnvFile } from "./lib/env-file.mjs";

const args = new Set(process.argv.slice(2));
const CONVEX_CLI = "node_modules/convex/bin/main.js";
// Compose secrets live in docker/.env, away from the Next.js app, which loads ./.env.
const COMPOSE = ["compose", "-f", "docker/compose.yml"];
const COMPOSE_ENV = "docker/.env";
const say = (message) => console.log(`\n▸ ${message}`);
const secret = (bytes = 32) => randomBytes(bytes).toString("base64url");

function run(command, commandArgs, options = {}) {
  // Run the Convex CLI through node directly: no shell, so no quoting surprises on Windows.
  const [file, fileArgs] =
    command === "convex" ? [process.execPath, [CONVEX_CLI, ...commandArgs]] : [command, commandArgs];
  const result = spawnSync(file, fileArgs, {
    stdio: options.capture ? ["ignore", "pipe", "inherit"] : "inherit",
    encoding: "utf8",
  });
  if (result.status !== 0) {
    throw new Error(`${command} ${commandArgs.slice(0, 3).join(" ")} … exited with ${result.status}`);
  }
  return result.stdout ?? "";
}

// ── 1. Local secrets ───────────────────────────────────────────────────────
say("Local secrets (docker/.env)");
const composeEnv = readEnvFile(COMPOSE_ENV);
const generated = {};
const ensure = (key, make) => {
  if (!composeEnv[key]) generated[key] = make();
};
ensure("N8N_ENCRYPTION_KEY", () => secret());
ensure("N8N_RUNNERS_AUTH_TOKEN", () => secret());
ensure("CONVEX_INSTANCE_SECRET", () => randomBytes(32).toString("hex"));
ensure("LENDLOOP_CONVEX_TO_N8N_SECRET", () => secret());
ensure("LENDLOOP_N8N_TO_CONVEX_SECRET", () => secret());
let ownerPassword = composeEnv.N8N_OWNER_PASSWORD;
if (!ownerPassword || !composeEnv.N8N_OWNER_PASSWORD_HASH) {
  ownerPassword = `${secret(12)}-Aa1`; // n8n wants upper, lower and a digit
  generated.N8N_OWNER_PASSWORD = ownerPassword;
  generated.N8N_OWNER_PASSWORD_HASH = bcrypt.hashSync(ownerPassword, 10);
}
if (Object.keys(generated).length) {
  updateEnvFile(COMPOSE_ENV, generated, {
    quote: true,
    header:
      "# Local-only secrets for docker compose, generated by `npm run setup`. Never commit this file.\n" +
      "# Rotate a secret by deleting its line and re-running setup.\n",
  });
  console.log(`  generated: ${Object.keys(generated).join(", ")}`);
} else {
  console.log("  all present");
}
const env = { ...composeEnv, ...generated };

// ── 2. Docker ──────────────────────────────────────────────────────────────
if (!args.has("--skip-docker")) {
  say("Starting Docker services (first run downloads images; a few minutes)");
  run("docker", [...COMPOSE, "up", "-d", "--wait"]);
}

// ── 3. Convex CLI → local backend ──────────────────────────────────────────
say("Connecting the Convex CLI to the local backend (.env.local)");
const local = readEnvFile(".env.local");
let adminKey = local.CONVEX_SELF_HOSTED_ADMIN_KEY;
if (!adminKey) {
  const output = run("docker", [...COMPOSE, "exec", "-T", "convex-backend", "./generate_admin_key.sh"], {
    capture: true,
  });
  adminKey = output.trim().split(/\r?\n/).filter(Boolean).at(-1);
  if (!adminKey?.includes("|")) throw new Error(`Couldn't read the Convex admin key from:\n${output}`);
}

const publishableKey = local.NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY;
let clerkIssuer = local.CLERK_FRONTEND_API_URL;
if (!clerkIssuer && publishableKey?.startsWith("pk_")) {
  // pk_test_<base64("<frontend-api-host>$")>, see Clerk's buildPublishableKey.
  const host = Buffer.from(publishableKey.split("_")[2], "base64").toString("utf8").replace(/\$$/, "");
  clerkIssuer = `https://${host}`;
}

updateEnvFile(
  ".env.local",
  {
    CONVEX_SELF_HOSTED_URL: "http://127.0.0.1:3210",
    CONVEX_SELF_HOSTED_ADMIN_KEY: adminKey,
    NEXT_PUBLIC_CONVEX_URL: "http://127.0.0.1:3210",
    NEXT_PUBLIC_CONVEX_SITE_URL: "http://127.0.0.1:3211",
    NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY: publishableKey ?? "",
    CLERK_SECRET_KEY: local.CLERK_SECRET_KEY ?? "",
    CLERK_FRONTEND_API_URL: clerkIssuer ?? "",
    NEXT_PUBLIC_CLERK_SIGN_IN_URL: "/sign-in",
    NEXT_PUBLIC_CLERK_SIGN_UP_URL: "/sign-up",
    // Never let Clerk silently create a throwaway "keyless" app: use your own keys.
    NEXT_PUBLIC_CLERK_KEYLESS_DISABLED: "true",
  },
  {
    // A cloud or anonymous deployment would win over the self-hosted one.
    remove: ["CONVEX_DEPLOYMENT"],
    header: "# Next.js + Convex CLI settings for local development. Git-ignored.\n",
  },
);

if (!clerkIssuer) {
  console.warn(
    "\n  ! No Clerk keys yet. Add NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY and CLERK_SECRET_KEY to .env.local\n" +
      "    (Clerk dashboard → API keys) and run `npm run setup` again. Until then the public page\n" +
      "    works but sign-in doesn't.",
  );
}

// ── 4. Optional: Clerk JWT template ────────────────────────────────────────
if (args.has("--clerk-jwt-template")) {
  say('Ensuring a "convex" JWT template exists in Clerk');
  if (!local.CLERK_SECRET_KEY) throw new Error("CLERK_SECRET_KEY is missing from .env.local");
  const headers = { Authorization: `Bearer ${local.CLERK_SECRET_KEY}`, "Content-Type": "application/json" };
  const templates = await (await fetch("https://api.clerk.com/v1/jwt_templates", { headers })).json();
  if (Array.isArray(templates) && templates.some((t) => t.name === "convex")) {
    console.log("  already exists");
  } else {
    // Only what LendLoop reads: audience, first name, email and whether it's verified.
    const response = await fetch("https://api.clerk.com/v1/jwt_templates", {
      method: "POST",
      headers,
      body: JSON.stringify({
        name: "convex",
        lifetime: 60,
        allowed_clock_skew: 5,
        claims: {
          aud: "convex",
          given_name: "{{user.first_name}}",
          email: "{{user.primary_email_address}}",
          email_verified: "{{user.email_verified}}",
        },
      }),
    });
    if (!response.ok) throw new Error(`Clerk said ${response.status}: ${await response.text()}`);
    console.log("  created");
  }
}

// ── 5. Convex deployment env + push ────────────────────────────────────────
say("Setting Convex environment variables");
const convexEnv = {
  CLERK_FRONTEND_API_URL: clerkIssuer || "https://clerk-not-configured.invalid",
  LENDLOOP_APP_URL: local.LENDLOOP_APP_URL || "http://localhost:3000",
  LENDLOOP_TIMEZONE: env.LENDLOOP_TIMEZONE || "UTC",
  // Convex and n8n share the compose network, so Convex calls n8n by service name.
  N8N_LOAN_EVENTS_WEBHOOK_URL: "http://n8n:5678/webhook/lendloop/loan-events",
  LENDLOOP_CONVEX_TO_N8N_SECRET: env.LENDLOOP_CONVEX_TO_N8N_SECRET,
  LENDLOOP_N8N_TO_CONVEX_SECRET: env.LENDLOOP_N8N_TO_CONVEX_SECRET,
};
for (const [name, value] of Object.entries(convexEnv)) {
  run("convex", ["env", "set", name, value], { capture: true });
  console.log(`  ${name}`);
}

say("Pushing Convex functions and schema");
run("convex", ["dev", "--once"]);

console.log(`
✔ LendLoop is set up.

  App              npm run dev  →  http://localhost:3000
  n8n              http://localhost:5678   ${env.N8N_OWNER_EMAIL || "owner@lendloop.example"} / ${ownerPassword}
  Mailpit (inbox)  http://localhost:8025
  Convex dashboard http://localhost:6791   admin key: see CONVEX_SELF_HOSTED_ADMIN_KEY in .env.local

  Make yourself an admin after signing in once:
    npm run make-admin -- you@example.com
`);
if (!existsSync(".env.local")) process.exitCode = 1;
